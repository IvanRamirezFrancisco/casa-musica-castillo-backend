-- Only hashes of opaque challenges and BCrypt email codes are stored.
CREATE TABLE auth.login_challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_hash CHAR(64) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    purpose VARCHAR(20) NOT NULL CHECK (purpose = 'LOGIN_2FA'),
    created_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    consumed_at TIMESTAMP,
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count BETWEEN 0 AND 5),
    email_code_hash VARCHAR(100),
    CHECK (expires_at > created_at)
);
CREATE INDEX login_challenges_user_idx ON auth.login_challenges(user_id);
CREATE INDEX login_challenges_expiry_idx ON auth.login_challenges(expires_at);

-- One bounded row per user. Limits survive restarts and challenge replacement.
CREATE TABLE auth.login_factor_limits (
    user_id BIGINT PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    window_start TIMESTAMP NOT NULL,
    challenges INTEGER NOT NULL DEFAULT 0 CHECK (challenges >= 0),
    sends INTEGER NOT NULL DEFAULT 0 CHECK (sends >= 0),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0)
);
